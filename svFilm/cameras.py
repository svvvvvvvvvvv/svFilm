#   把 anchors 描述成"在用"，属**文档失真**，已改。
#   保留它们的理由：`ENTRY_TONE = False` 时走 `io.apply_entry_curve()`，那时 anchors
#   就是**唯一**的形状来源 —— 留作 A/B 通道与历史留档，**不是**当前生产路径。
#   要用零点，请用 `entry_zero_ev()`，别自己去拆 anchors。
