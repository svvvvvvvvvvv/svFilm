# 富士「动态范围」档位的**额外**欠曝（不含那 0.72 的基底）。
# 来源：darktable 官方 lua 脚本 fujifilm_dynamic_range 的实测值
#   RawExposureBias 总量：100 DR -> −0.72 EV ／ 200 DR -> −1.72 EV ／ 400 DR -> −2.72 EV
