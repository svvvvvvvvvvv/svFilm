# 同口径：RapidRAW issue #711（DevelopmentDynamicRange 100/200/400 -> 0/+1/+2 EV）。
FUJI_DR_BIAS = {100: 0.0, 200: 1.0, 400: 2.0}


def dr_bias_ev(dr):
    """富士 DR 档 -> 要**额外**补的 EV（不含机型基底）。None / 不认识 -> None。"""
    if dr is None:
        return None
    try:
        return FUJI_DR_BIAS.get(int(dr))
    except (TypeError, ValueError):
        return None


