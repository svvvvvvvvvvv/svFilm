# ---- 肤色「正向达标」（09-13 SV 拍板「全」档）----
# 为什么：L3 原来只做"保护"（把风格层收掉的色还回来），没有"往目标靠"的动作。
# 「全对齐」基准的退黄是按**整图中位**解的，而脸比整图更暖 ⇒ 全局退黄把脸一起退冷。
# 实测（`_debug/analysis/skin_master_ruler.md`，33 位作者，**用 svFilm 自己的面膜**量的）：
#   大师脸区 a* P25 13.7 / P50 16.3 / P75 17.9；b* P25 14.8 / P50 18.5 / P75 20.5；L* P50 62.7
#   机内 JPEG 的脸 a*≈15.3 / b*≈17.9（≈ 大师）；我们成片只有 a*≈12.2 / b*≈12.4 ⇒ 偏冷偏淡
# 规则（**逐像素**，不用任何"整体统计量"）：
#   每个皮肤像素自己看"离目标还差多少"，差多少补多少（单像素位移设上限）；
#   两个轴都低于目标才补（避免把"一轴已经很高"的彩色物体 —— 比如粉衣服 —— 一起推暖）。
#   ⚠ 曾经试过"用全图肤色的中位算一个位移、再作用到所有皮肤像素"：不行 ——
#     掩膜会把粉衣服/木色/路面算进来（实测园岭某张 15.3% 的像素被判成皮肤），
#     中位被拉低之后，人脸会被**推过头**（实测 b* 冲到 20.4，目标 18.5）。
#     逐像素做就没有这个问题：人脸落在目标上，彩色物体自己不动。
